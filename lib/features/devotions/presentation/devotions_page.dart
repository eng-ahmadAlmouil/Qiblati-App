class _TextItems extends StatelessWidget {
  const _TextItems({required this.items});
  final List<(String, String)> items;

  @override
  Widget build(BuildContext context) {
    return ListView.separated(
      padding: const EdgeInsets.all(AppDimensions.pagePadding),
      itemCount: items.length,
      separatorBuilder: (_, _) => const SizedBox(height: 12),
      itemBuilder: (context, index) => LiquidGlass(
        padding: const EdgeInsets.all(18),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Text(items[index].$1,
                style: Theme.of(context).textTheme.titleMedium?.copyWith(
                  color: AppColors.greenDark, fontWeight: FontWeight.w800)),
            const SizedBox(height: 8),
            Text(items[index].$2,
                style: Theme.of(context).textTheme.bodyLarge?.copyWith(height: 1.9)),
          ],
        ),
      ),
    );
  }
}

